_schema_ready = False
_schema_lock = threading.Lock()


def init_db():
    with db() as conn:

        conn.execute("SET TIME ZONE 'Asia/Tehran'")

        conn.execute("""
            CREATE TABLE IF NOT EXISTS categories (
                id SERIAL PRIMARY KEY,
                name TEXT UNIQUE NOT NULL
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS brands (
                id SERIAL PRIMARY KEY,
                name TEXT UNIQUE NOT NULL,
                created_at TIMESTAMPTZ DEFAULT NOW()
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS products (
                id SERIAL PRIMARY KEY,
                category_id INTEGER
                    REFERENCES categories(id) ON DELETE RESTRICT,
                name TEXT NOT NULL,
                description TEXT DEFAULT '',
                price BIGINT NOT NULL DEFAULT 0
                    CHECK (price >= 0),
                image_url TEXT,
                created_at TIMESTAMPTZ DEFAULT NOW()
            )
        """)

        conn.execute("""
            ALTER TABLE products
            ADD COLUMN IF NOT EXISTS stock INTEGER NOT NULL DEFAULT 0
        """)

        conn.execute("""
            ALTER TABLE products
            ADD COLUMN IF NOT EXISTS min_stock INTEGER NOT NULL DEFAULT 2
        """)

        conn.execute("""
            ALTER TABLE products
            ADD COLUMN IF NOT EXISTS brand_id INTEGER
            REFERENCES brands(id) ON DELETE SET NULL
        """)

        conn.execute("""
            ALTER TABLE products
            ADD COLUMN IF NOT EXISTS is_active BOOLEAN NOT NULL DEFAULT TRUE
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS stock_movements (
                id BIGSERIAL PRIMARY KEY,
                product_id INTEGER NOT NULL
                    REFERENCES products(id) ON DELETE RESTRICT,
                movement_type TEXT NOT NULL
                    CHECK (movement_type IN
                    ('in', 'out', 'adjustment', 'sale', 'return')),
                quantity INTEGER NOT NULL,
                note TEXT DEFAULT '',
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS sales (
                id BIGSERIAL PRIMARY KEY,
                invoice_number BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
                total_amount BIGINT NOT NULL DEFAULT 0,
                discount BIGINT NOT NULL DEFAULT 0,
                final_amount BIGINT NOT NULL DEFAULT 0,
                description TEXT DEFAULT '',
                status TEXT NOT NULL DEFAULT 'completed'
                    CHECK (status IN ('completed', 'cancelled')),
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS sale_items (
                id BIGSERIAL PRIMARY KEY,
                sale_id BIGINT NOT NULL
                    REFERENCES sales(id) ON DELETE RESTRICT,
                product_id INTEGER NOT NULL
                    REFERENCES products(id) ON DELETE RESTRICT,
                quantity INTEGER NOT NULL CHECK (quantity > 0),
                unit_price BIGINT NOT NULL CHECK (unit_price >= 0),
                line_total BIGINT NOT NULL CHECK (line_total >= 0)
            )
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_stock_product
            ON stock_movements(product_id)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_sales_created
            ON sales(created_at)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_sale_items_sale
            ON sale_items(sale_id)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_products_active
            ON products(is_active)
        """)


@app.before_request
def prepare_database():
    global _schema_ready

    if not _schema_ready:
        with _schema_lock:
            if not _schema_ready:
                init_db()
                _schema_ready = True


