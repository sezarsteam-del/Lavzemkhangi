@app.route("/admin/inventory", methods=["GET", "POST"])
@admin_required
def inventory():
    if request.method == "POST":
        try:
            product_id = int(request.form.get("product_id", ""))
            movement_type = request.form.get("movement_type", "")
            quantity = int(request.form.get("quantity", "0"))
            note = request.form.get("note", "").strip()

            if quantity <= 0:
                raise ValueError

            if movement_type not in ("in", "out", "adjustment"):
                raise ValueError

            with db() as conn:
                product = conn.execute("""
                    SELECT id, stock
                    FROM products
                    WHERE id = %s AND is_active = TRUE
                    FOR UPDATE
                """, (product_id,)).fetchone()

                if not product:
                    flash("محصول پیدا نشد.", "error")
                    return redirect(url_for("inventory"))

                old_stock = product["stock"]

                if movement_type == "in":
                    new_stock = old_stock + quantity
                    movement_quantity = quantity

                elif movement_type == "out":
                    if quantity > old_stock:
                        flash("موجودی برای این خروج کافی نیست.", "error")
                        return redirect(url_for("inventory"))

                    new_stock = old_stock - quantity
                    movement_quantity = quantity

                else:
                    new_stock = quantity
                    movement_quantity = new_stock - old_stock

                conn.execute("""
                    UPDATE products SET stock = %s WHERE id = %s
                """, (new_stock, product_id))

                conn.execute("""
                    INSERT INTO stock_movements
                        (product_id, movement_type, quantity, note)
                    VALUES (%s, %s, %s, %s)
                """, (
                    product_id, movement_type,
                    movement_quantity, note
                ))

            flash("تغییر موجودی ثبت شد.", "success")

        except (ValueError, TypeError):
            flash("اطلاعات ورود یا خروج معتبر نیست.", "error")

        return redirect(url_for("inventory"))

    with db() as conn:
        products = conn.execute("""
            SELECT id, name, stock, min_stock
            FROM products
            WHERE is_active = TRUE
            ORDER BY name
        """).fetchall()

        movements = conn.execute("""
            SELECT
                m.*,
                p.name AS product_name
            FROM stock_movements m
            JOIN products p ON p.id = m.product_id
            ORDER BY m.created_at DESC
            LIMIT 100
        """).fetchall()

    return render_template(
        "inventory.html",
        products=products,
        movements=movements
    )


