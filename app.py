@app.route("/admin/sales/<int:sale_id>/cancel", methods=["POST"])
@admin_required
def cancel_sale(sale_id):

    with db() as conn:

        sale = conn.execute("""
            SELECT *
            FROM sales
            WHERE id = %s
            FOR UPDATE
        """, (sale_id,)).fetchone()

        if not sale:
            abort(404)

        if sale["status"] == "cancelled":
            flash("این فاکتور قبلاً لغو شده است.", "error")
            return redirect(url_for("sales"))

        items = conn.execute("""
            SELECT product_id, quantity
            FROM sale_items
            WHERE sale_id = %s
            ORDER BY product_id
        """, (sale_id,)).fetchall()

        for item in items:

            conn.execute("""
                UPDATE products
                SET stock = stock + %s
                WHERE id = %s
            """, (
                item["quantity"],
                item["product_id"]
            ))

            conn.execute("""
                INSERT INTO stock_movements
                    (product_id, movement_type, quantity, note)
                VALUES (%s, 'return', %s, %s)
            """, (
                item["product_id"],
                item["quantity"],
                f"برگشت از فاکتور {sale['invoice_number']}"
            ))

        conn.execute("""
            UPDATE sales
            SET status = 'cancelled'
            WHERE id = %s
        """, (sale_id,))

    flash("فاکتور لغو شد و موجودی کالاها برگشت.", "success")
    return redirect(url_for("sales"))


